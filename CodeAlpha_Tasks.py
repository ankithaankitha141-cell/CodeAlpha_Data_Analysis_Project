import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

# --- TASK 2: Exploratory Data Analysis (EDA) ---
print("Starting Task 2: Exploratory Data Analysis...\n")
df = sns.load_dataset('titanic') # We are using a built-in dataset about the Titanic

print("1. Data Information:")
df.info()

print("\n2. Checking for missing data:")
print(df.isnull().sum())

# --- TASK 3: Data Visualization ---
print("\nStarting Task 3: Data Visualization...")
plt.figure(figsize=(10, 4))

# First Chart
plt.subplot(1, 2, 1)
sns.countplot(x='survived', data=df, palette='Set2')
plt.title('Passenger Survival Count')

# Second Chart
plt.subplot(1, 2, 2)
sns.histplot(df['age'].dropna(), bins=30, color='skyblue')
plt.title('Passenger Age Distribution')

plt.tight_layout()
plt.show()